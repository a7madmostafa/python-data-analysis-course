"""Write the data the lesson widgets read:
  site/assets/data/sales.js     the completed NileCart orders as compact arrays (NumPy, Descriptive statistics)
  site/assets/data/nilecart.js  the whole sales table, profiled column by column (Introduction)
  site/assets/data/linalg.js    product prices and the Q @ P example (Linear algebra)
  site/assets/data/numpy.js     revenue per month as a (2, 12) years x months matrix (NumPy)
  site/assets/data/stats.js     one customer's order lines, for the drag-a-value widget (Descriptive statistics)
  site/assets/data/pandas.js    the sales table, compact, for the loc/iloc and filter widgets (Pandas basics)
  site/assets/data/grouping.js  a 12-line sample and two tiny raw tables, for the groupby and join widgets (Grouping & joining)
  site/assets/data/cleaning.js  the raw orders.csv and governorate spellings, for the pipeline and text widgets (Light cleaning)
  site/assets/data/viz.js       small summaries for the chart-chooser and fix-the-chart widgets (Why visualize)

    python build/export_site_data.py
"""
from pathlib import Path
import json

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
CATS = ["Stationery", "Accessories", "Furniture", "Electronics"]
SEGS = ["Consumer", "Small Business", "Corporate"]

s = pd.read_csv(ROOT / "data" / "nilecart" / "sales.csv")
o = s[s["status"] == "completed"]
data = {
    "cats": CATS,
    "segs": SEGS,
    "revenue": o["revenue"].round().astype(int).tolist(),
    "profit": o["profit"].round().astype(int).tolist(),
    "unit_price": o["unit_price"].round().astype(int).tolist(),
    "quantity": o["quantity"].astype(int).tolist(),
    "cat": o["category"].map(CATS.index).tolist(),
    "seg": [SEGS.index(v) if v in SEGS else -1 for v in o["segment"]],
}
out = ROOT / "website" / "site" / "assets" / "data" / "sales.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("/* NileCart completed orders, generated by build/export_site_data.py */\nwindow.SALES = "
               + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", out, len(o), "orders")

# ---------- site/assets/data/nilecart.js: the whole sales table, profiled, for the Introduction lesson ----------
KINDS = {"order_id": "id", "customer_id": "id", "product_id": "id", "order_date": "datetime", "name": "text",
         "quantity": "discrete", "discount": "discrete",
         **{c: "nominal" for c in ["governorate", "region", "segment", "product_name", "category", "status"]},
         **{c: "continuous" for c in ["unit_price", "gross", "revenue", "unit_cost", "profit"]}}
s["order_date"] = pd.to_datetime(s["order_date"])


def profile(c):
    col, kind = s[c], KINDS[c]
    p = {"name": c, "kind": kind, "dtype": str(col.dtype), "unique": int(col.nunique()), "missing": int(col.isna().sum())}
    if kind in ("continuous", "discrete", "id"):
        p.update(min=float(col.min()), median=float(col.median()), mean=round(float(col.mean()), 2), max=float(col.max()))
    if kind == "continuous":
        counts, edges = np.histogram(col, bins=24)
        p["hist"] = {"counts": counts.tolist(), "edges": edges.round(2).tolist()}
    elif kind in ("discrete", "nominal"):
        vc = col.value_counts()
        if kind == "discrete":
            vc = vc.sort_index()
        p["counts"] = [[str(k) if kind == "nominal" else float(k), int(v)] for k, v in vc.head(10).items()]
        p["others"] = int(vc.iloc[10:].sum())
    elif kind == "datetime":
        m = col.dt.to_period("M").value_counts().sort_index()
        p.update(first=str(col.min().date()), last=str(col.max().date()), months=[[str(k), int(v)] for k, v in m.items()])
    elif kind == "text":
        p["examples"] = col.drop_duplicates().head(4).tolist()
    return p


done = s[s["status"] == "completed"]
by = done.groupby([done["order_date"].dt.year, done["order_date"].dt.month])["revenue"]
monthly = {str(y): {"orders": [int(by.size().get((y, m), 0)) for m in range(1, 13)],
                    "revenue": [round(float(by.sum().get((y, m), 0))) for m in range(1, 13)],
                    "median": [round(float(by.median().get((y, m), 0))) for m in range(1, 13)]} for y in (2024, 2025)}
yr = done.groupby(done["order_date"].dt.year)["revenue"]
big = done[done["revenue"] > 100_000].groupby(done["order_date"].dt.year)["revenue"]
yearly = {str(y): {"orders": int(yr.size()[y]), "revenue": round(float(yr.sum()[y])), "median": round(float(yr.median()[y])),
                   "big_orders": int(big.size()[y]), "big_revenue": round(float(big.sum()[y]))} for y in (2024, 2025)}
head_rows = s.head(8).assign(order_date=s["order_date"].dt.strftime("%Y-%m-%d")).astype(object).where(s.head(8).notna(), None)
nile = {"rows": len(s), "columns": list(s.columns), "head": head_rows.values.tolist(),
        "profiles": [profile(c) for c in s.columns], "monthly": monthly, "yearly": yearly}
out = ROOT / "website" / "site" / "assets" / "data" / "nilecart.js"
out.write_text("/* NileCart sales.csv profiled for the Introduction lesson, generated by build/export_site_data.py */\n"
               "window.NILECART = " + json.dumps(nile, separators=(",", ":"), ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out, f"({out.stat().st_size // 1024} KB)")

# ---------- site/assets/data/linalg.js: product prices and the Q @ P example, for the Linear algebra lesson ----------
prods = pd.read_csv(ROOT / "data" / "nilecart" / "products.csv").set_index("product_name")
ELEC = ["Laptop", "Phone", "Tablet", "Monitor"]
d25 = done[(done["order_date"].dt.year == 2025) & done["product_name"].isin(ELEC)]
Q = d25.pivot_table(index=d25["order_date"].dt.quarter, columns="product_name", values="quantity", aggfunc="sum").reindex(columns=ELEC)
la = {"products": [[n, int(r.list_price), int(r.unit_cost), r.category] for n, r in prods.iterrows()],
      "elec": ELEC, "Q": Q.astype(int).values.tolist(),
      "P": prods.loc[ELEC, ["list_price", "unit_cost"]].astype(int).values.tolist()}
out = ROOT / "website" / "site" / "assets" / "data" / "linalg.js"
out.write_text("/* NileCart product prices and the quarterly Q @ P example, generated by build/export_site_data.py */\n"
               "window.LINALG = " + json.dumps(la, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", out, f"({out.stat().st_size // 1024} KB)")

# ---------- site/assets/data/numpy.js: revenue per month, (2, 12) years x months, for the NumPy lesson ----------
mon = done.groupby(done["order_date"].dt.to_period("M"))["revenue"].sum()
M = mon.to_numpy().reshape(2, 12)
out = ROOT / "website" / "site" / "assets" / "data" / "numpy.js"
out.write_text("/* NileCart revenue per month, 2024-2025, as a (2, 12) matrix, generated by build/export_site_data.py */\n"
               "window.NUMPY = " + json.dumps({"years": [2024, 2025], "M": M.round().astype(int).tolist()}, separators=(",", ":")) + ";\n",
               encoding="utf-8")
print("wrote", out)

# ---------- site/assets/data/stats.js: one customer's 9 completed lines, for the Descriptive statistics lesson ----------
yh = done[done["customer_id"] == 18]
st = {"name": yh["name"].iloc[0], "revenue": sorted(round(float(v), 1) for v in yh["revenue"])}
out = ROOT / "website" / "site" / "assets" / "data" / "stats.js"
out.write_text("/* One NileCart customer's completed order lines, generated by build/export_site_data.py */" + chr(10) +
               "window.STATS = " + json.dumps(st, separators=(",", ":")) + ";" + chr(10), encoding="utf-8")
print("wrote", out)

# ---------- site/assets/data/pandas.js: the sales table, compact, for the Pandas basics lesson widgets ----------
pdf = pd.read_csv(ROOT / "data" / "nilecart" / "sales.csv")
lev = {c: sorted(pdf[c].unique().tolist()) for c in ["name", "product_name", "category", "region", "status"]}
pa = {"levels": lev,
      "order_id": pdf["order_id"].tolist(), "date": pdf["order_date"].tolist(),
      **{c: pdf[c].map({v: i for i, v in enumerate(lev[c])}).tolist() for c in lev},
      "quantity": pdf["quantity"].astype(int).tolist(), "revenue": pdf["revenue"].round(2).tolist()}
out = ROOT / "website" / "site" / "assets" / "data" / "pandas.js"
out.write_text("/* NileCart sales.csv, column by column with text as codes, generated by build/export_site_data.py */" + chr(10) +
               "window.PANDAS = " + json.dumps(pa, separators=(",", ":"), ensure_ascii=False) + ";" + chr(10), encoding="utf-8")
print("wrote", out, f"({out.stat().st_size // 1024} KB)")

# ---------- site/assets/data/grouping.js: a 12-line sample (groupby widget) and two tiny raw tables (join widget) ----------
gs = pd.read_csv(ROOT / "data" / "nilecart" / "sales.csv")
gs = gs[gs["status"] == "completed"].sample(12, random_state=3)
raw_o = pd.read_csv(ROOT / "data" / "nilecart" / "orders.csv")
raw_c = pd.read_csv(ROOT / "data" / "nilecart" / "customers.csv")
pick = (pd.concat([raw_o[raw_o["customer_id"] == 50].sort_values("order_id").head(2),
                   raw_o[raw_o["customer_id"] == 34].sort_values("order_id").head(1),
                   raw_o[raw_o["customer_id"] == 95].sort_values("order_id").head(1),
                   raw_o[raw_o["order_id"] == 10011]])
        .sort_values("order_id"))
gc = raw_c[raw_c["customer_id"].isin([34, 50, 95, 181])].assign(name=lambda x: x["name"].str.strip().str.title())
gr = {"sample": gs[["order_id", "product_name", "category", "region", "segment", "revenue"]].values.tolist(),
      "orders": pick[["order_id", "customer_id", "product_id", "quantity"]].astype({"quantity": "Int64"}).values.tolist(),
      "customers": gc[["customer_id", "name", "segment"]].values.tolist()}
out = ROOT / "website" / "site" / "assets" / "data" / "grouping.js"
out.write_text("/* NileCart samples for the Grouping & joining lesson, generated by build/export_site_data.py */" + chr(10) +
               "window.GROUPING = " + json.dumps(gr, separators=(",", ":"), default=int) + ";" + chr(10), encoding="utf-8")
print("wrote", out)

# ---------- site/assets/data/cleaning.js: the raw orders.csv and the raw governorate spellings, for the Light cleaning lesson ----------
ro = pd.read_csv(ROOT / "data" / "nilecart" / "orders.csv")
rc = pd.read_csv(ROOT / "data" / "nilecart" / "customers.csv")
STATUS = ["completed", "shipped", "returned", "cancelled"]
nul = lambda s: [None if pd.isna(v) else v for v in s]
cl = {"status_levels": STATUS,
      "order_id": ro["order_id"].tolist(), "date": ro["order_date"].tolist(),
      "quantity": nul(ro["quantity"]), "unit_price": ro["unit_price"].tolist(), "discount": nul(ro["discount"]),
      "status": [None if pd.isna(v) else STATUS.index(v) for v in ro["status"]],
      "gov_raw": rc["governorate"].tolist(),
      "gov_ref": pd.read_csv(ROOT / "data" / "nilecart" / "governorates.csv")["governorate"].tolist()}
out = ROOT / "website" / "site" / "assets" / "data" / "cleaning.js"
out.write_text("/* NileCart raw orders.csv and customer governorates, generated by build/export_site_data.py */" + chr(10) +
               "window.CLEANING = " + json.dumps(cl, separators=(",", ":")) + ";" + chr(10), encoding="utf-8")
print("wrote", out, f"({out.stat().st_size // 1024} KB)")

# ---------- site/assets/data/viz.js: small NileCart summaries for the chart-chooser and fix-the-chart widgets ----------
vd = done.copy()
vd["month"] = vd["order_date"].dt.to_period("M").astype(str)
lr = np.log10(vd["revenue"])
hc, he = np.histogram(lr, bins=30)
sc = vd.sample(400, random_state=1)
regv = vd.groupby("region")["revenue"].sum().drop("Unknown")
catv = vd.groupby("category")["revenue"].sum()
pvv = vd.pivot_table(index="region", columns="category", values="revenue", aggfunc="sum", fill_value=0).drop(index="Unknown")
vz = {"months": sorted(vd["month"].unique().tolist()),
      "monthly": vd.groupby("month")["revenue"].sum().round().astype(int).tolist(),
      "regions": regv.index.tolist(), "region_rev": regv.round().astype(int).tolist(),
      "cats": catv.index.tolist(), "cat_rev": catv.round().astype(int).tolist(),
      "hist": {"counts": hc.tolist(), "edges": he.round(3).tolist()},
      "scatter": sc[["unit_price", "revenue"]].round(1).values.tolist(),
      "first": vd["revenue"].head(60).round().astype(int).tolist(),
      "pivot": {"rows": pvv.index.tolist(), "cols": pvv.columns.tolist(), "values": pvv.round().astype(int).values.tolist()}}
out = ROOT / "website" / "site" / "assets" / "data" / "viz.js"
out.write_text("/* NileCart summaries for the Why-visualize lesson widgets, generated by build/export_site_data.py */" + chr(10) +
               "window.VIZ = " + json.dumps(vz, separators=(",", ":")) + ";" + chr(10), encoding="utf-8")
print("wrote", out, f"({out.stat().st_size // 1024} KB)")
