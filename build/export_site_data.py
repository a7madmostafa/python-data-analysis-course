"""Write site/assets/data/sales.js: the completed NileCart orders as compact arrays for the lesson widgets.

    python build/export_site_data.py
"""
from pathlib import Path
import json

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CATS = ["Stationery", "Accessories", "Furniture", "Electronics"]
SEGS = ["Consumer", "Small Business", "Corporate"]

s = pd.read_csv(ROOT / "data" / "sales.csv")
o = s[s["status"] == "completed"]
data = {
    "cats": CATS,
    "segs": SEGS,
    "revenue": o["revenue"].round().astype(int).tolist(),
    "profit": o["profit"].round().astype(int).tolist(),
    "unit_price": o["unit_price"].round().astype(int).tolist(),
    "quantity": o["quantity"].astype(int).tolist(),
    "cat": o["category"].map(CATS.index).tolist(),
    "seg": [SEGS.index(v) if v in SEGS else -1 for v in o["segment"]],
}
out = ROOT / "site" / "assets" / "data" / "sales.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("/* NileCart completed orders, generated by build/export_site_data.py */\nwindow.SALES = "
               + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", out, len(o), "orders")
